function hoursAgo(h) {
  const d = new Date();
  d.setHours(d.getHours() - h);
  return d.toISOString();
}

function minutesAgo(m) {
  const d = new Date();
  d.setMinutes(d.getMinutes() - m);
  return d.toISOString();
}

function daysAgoDate(d) {
  const date = new Date();
  date.setDate(date.getDate() - d);
  return date.toISOString().split('T')[0];
}

function generateHourlyActivity(baseGrazing, baseResting, baseWalking) {
  const hours = [
    '00:00', '02:00', '04:00', '06:00', '08:00',
    '10:00', '12:00', '14:00', '16:00', '18:00', '20:00', '22:00'
  ];
  return hours.map((h, i) => {
    const isDay = i >= 3 && i <= 8;
    const grazing = isDay ? Math.min(60, Math.round(baseGrazing * 0.45 + (i % 3) * 8)) : Math.round(baseGrazing * 0.1);
    const resting = isDay ? Math.round(baseResting * 0.15) : Math.min(60, Math.round(baseResting * 0.45 + (i % 2) * 5));
    const walking = isDay ? Math.min(30, Math.round(baseWalking * 0.3 + (i % 4) * 4)) : 5;
    const active = Math.max(0, 60 - resting);
    return { hour: h, grazing, resting, walking, active };
  });
}

function generateSensorHistory(baseTemp, isNominal) {
  return [6, 5, 4, 3, 2, 1].map((h) => ({
    timestamp: hoursAgo(h),
    temperature: Number((baseTemp + (Math.sin(h) * 0.2)).toFixed(1)),
    accelMag: Number((isNominal ? 9.8 + Math.cos(h) * 0.15 : 10.4 + Math.sin(h) * 0.8).toFixed(2)),
    gyroMag: Number((isNominal ? 1.2 + Math.abs(Math.sin(h)) * 1.5 : 8.5 + Math.cos(h) * 4.2).toFixed(1)),
    battery: Math.max(10, 85 - h * 2),
  }));
}

